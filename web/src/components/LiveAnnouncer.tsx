/**
 * Отдельный канал озвучивания стрима (084, W2).
 *
 * Почему не `aria-live` на самой ленте: ассистентский ответ меняется десятки раз
 * в секунду, и polite-регион начинает либо захлёбываться, либо (что хуже)
 * перечитывать уже сказанное. Поэтому лента — `role="log"` с `aria-live="off"`
 * (навигация работает, объявлений нет), а прогресс идёт сюда, по одному
 * закрытому блоку за раз.
 *
 * Почему ДВА слота, а не один:
 *
 *  - `aria-atomic="true"` объявляет ВСЁ содержимое региона на каждое изменение.
 *    Если дописывать блоки в один регион, каждый новый блок перечитывал бы
 *    весь ответ — ровно та лавина, ради ухода от которой канал и заведён.
 *  - Регион с неизменным текстом не мутирует, и повторный одинаковый блок
 *    (два одинаковых абзаца) не был бы объявлен вовсе.
 *
 * Поэтому содержимое слота ЗАМЕНЯЕТСЯ, а слоты чередуются по чётности `seq`:
 * текст пишется в один, второй очищается. Оба региона смонтированы с первого
 * рендера и никогда не переключают `aria-live` (переключение `off → polite`
 * после появления контента часть пар «браузер + скринридер» не объявляет).
 */
export type Announcement = {
  /** Монотонный номер: чётность выбирает слот, значение — признак нового события. */
  seq: number;
  text: string;
};

export function LiveAnnouncer({ announcement }: { announcement: Announcement | null }) {
  const text = announcement?.text.trim() ?? '';
  const first = announcement !== null && announcement.seq % 2 === 0;

  return (
    <>
      <span className="sr-only live-announcer" role="status" aria-live="polite" aria-atomic="true">
        {first ? text : ''}
      </span>
      <span className="sr-only live-announcer" role="status" aria-live="polite" aria-atomic="true">
        {first ? '' : text}
      </span>
    </>
  );
}
